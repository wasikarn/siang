BELOW = 'ฺุู'

def glyphs(s):
    # Windows Thai font shaping: what a PDF text layer holds when the font maps shifted glyphs to PUA.
    out = []
    for i, c in enumerate(s):
        p = s[i - 1] if i else ''
        n = s[i + 1] if i + 1 < len(s) else ''
        if c in UPV and p in TALL:
            out.append(UPV[c])
        elif c in TONES and n != 'ำ':
            k = TONES.index(c)
            j = i - 1
            while j >= 0 and s[j] in BELOW:
                j -= 1
            if p in UPV:
                out.append(UPLEFT[k] if i >= 2 and s[i - 2] in TALL else c)
            elif j >= 0 and s[j] in TALL:
                out.append(LOWLEFT[k])
            else:
                out.append(LOW[k])
        elif c == 'ญ' and n in BELOW:
            out.append('')
        elif c == 'ฐ' and n in BELOW:
            out.append('')
        elif c in BELOW and p in 'ฎฏ':
            out.append(''[BELOW.index(c)])
        else:
            out.append(c)
    return ''.join(out)

