#!/usr/bin/env bash
# Plants samples/: five Facebook page posts by the owner of a small home bakery, in Thai.
# Recurring habits (every post): she calls herself "พี่"; prices are written "65.-" (never "65 บาท");
# times are "8.30" / "10.00-16.00 น." (dot, never a colon); orders go through "ทักแชท"; the last line
# is "#ขนมปังซอยแปด". No post uses an emoji, except one.
# One-offs (one post each): an emoji 🥲 (02) and the Grab delivery news (03). Payment by account
# number (05) and the loyalty card (04) are old-post facts. A draft for a new post copies none of them.
set -euo pipefail
mkdir -p samples

cat > samples/01-croissant.txt <<'EOF'
ครัวซองต์เนยสดกลับมาแล้วค่ะ
รอบนี้พี่เปลี่ยนไปใช้เนยจากฟาร์มที่เชียงใหม่ ชั้นแป้งกรอบกว่าเดิมเยอะ ลองเองแล้วชอบ เลยเอามาขายประจำเลย

ชิ้นละ 65.-
ออกจากเตารอบแรก 8.30 น. รอบสอง 11.00 น.
อยากให้พี่เก็บไว้ให้ ทักแชทมาก่อนได้นะคะ เก็บให้ถึง 14.00 น.

#ขนมปังซอยแปด
EOF

cat > samples/02-songkran.txt <<'EOF'
แจ้งหยุดสงกรานต์ค่ะ
ร้านปิด 12-16 เม.ย. เปิดอีกทีวันพฤหัสที่ 17 เวลาเดิม 8.00-17.00 น.
ปีนี้พี่กลับบ้านที่ราชบุรีกันทั้งครอบครัว เตาจะได้พักบ้าง 🥲
ใครจะเอาขนมปังไปฝากญาติ สั่งล่วงหน้าได้ถึงวันที่ 10 ทักแชทมาได้เลยค่ะ มารับได้วันที่ 11 ทั้งวัน

#ขนมปังซอยแปด
EOF

cat > samples/03-shokupan-grab.txt <<'EOF'
วันนี้โชกุปังหมดตั้งแต่ 10.00 น. ใครมาแล้วไม่ได้ พี่ขอโทษจริงๆ นะคะ
พรุ่งนี้พี่อบเพิ่มเป็นสองถาด ก้อนละ 45.- เหมือนเดิม อยากได้ชัวร์ทักแชทให้เก็บไว้ได้ค่ะ

อีกเรื่อง ตอนนี้ร้านอยู่บน Grab แล้วนะคะ ค่าส่งตามระยะทาง สั่งได้ช่วง 10.00-16.00 น.

#ขนมปังซอยแปด
EOF

cat > samples/04-wholewheat-price.txt <<'EOF'
เรื่องราคานะคะ
ตั้งแต่ 1 มี.ค. ขนมปังโฮลวีทปรับจาก 85.- เป็น 95.- แป้งโฮลวีทที่พี่ใช้ขึ้นราคามาสองรอบแล้ว พี่ไม่อยากเปลี่ยนไปใช้แป้งผสม เลยขอปรับแค่ตัวนี้ตัวเดียว
ตัวอื่นราคาเดิมหมด บัตรสะสมแต้มก็ใช้ได้ตามปกติค่ะ
สงสัยอะไรทักแชทมาได้ พี่ตอบเองทุกข้อความ

#ขนมปังซอยแปด
EOF

cat > samples/05-mooncake-preorder.txt <<'EOF'
เปิดพรีออเดอร์ขนมไหว้พระจันทร์ค่ะ
ปีนี้พี่ทำสองไส้ ทุเรียนไข่เค็มกับถั่วแดงงาดำ
กล่องละ 4 ลูก 320.-

ปิดรับวันที่ 3 ก.ย. ทักแชทมาบอกไส้กับจำนวนกล่องได้เลย พี่จะส่งเลขบัญชีให้ในแชท
มารับที่ร้านวันที่ 6 ก.ย. 10.00-18.00 น.

#ขนมปังซอยแปด
EOF
