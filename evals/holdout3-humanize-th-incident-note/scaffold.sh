# สรุปเหตุการณ์ INC-2291 — ระบบ payment-webhook ล่ม

ในยุคดิจิทัลที่ความต่อเนื่องของบริการคือหัวใจสำคัญ เหตุการณ์ครั้งนี้ถือเป็นบทเรียนอันล้ำค่าที่จะช่วยยกระดับทีมของเราไปอีกขั้น 🚀

## ภาพรวม

เมื่อวันที่ 4 พ.ย. เวลา 14:05 ระบบ payment-webhook หยุดรับ callback จากธนาคารเป็นเวลา 47 นาที — ส่งผลให้ออเดอร์ 3,200 รายการค้างอยู่ในสถานะ pending

## สาเหตุ

ปัญหานี้ไม่ใช่แค่เรื่องทางเทคนิค แต่ยังสะท้อนถึงความท้าทายเชิงระบบที่ซับซ้อนอีกด้วย โดยต้นเหตุคือ TLS certificate ของ endpoint ฝั่งรับ callback หมดอายุ และไม่มี alert แจ้งล่วงหน้า

## การแก้ไข

คุณพิมพ์ชนกจากทีม SRE ได้ดำเนินการต่ออายุ certificate อย่างรวดเร็ว มีประสิทธิภาพ และไร้รอยต่อ — จากนั้นทีมได้ replay callback ที่ค้างทั้งหมดจนครบ

## บทสรุป

กล่าวโดยสรุป เหตุการณ์นี้ตอกย้ำถึงความสำคัญของการเฝ้าระวังเชิงรุก หวังว่าข้อมูลนี้จะเป็นประโยชน์ หากมีข้อสงสัยประการใด สามารถสอบถามได้ตลอดเวลานะครับ 😊
